CREATE TABLE news_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guid VARCHAR(1000) NOT NULL,
  title VARCHAR(1000) NOT NULL,
  link TEXT,
  description TEXT,
  publication_date VARCHAR(120),
  category VARCHAR(120),
  image_url TEXT,
  fecha_procesamiento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  news_log_id BIGINT NOT NULL,

  CONSTRAINT uq_news_items_guid UNIQUE (guid),
  CONSTRAINT fk_news_items_news_log
  FOREIGN KEY (news_log_id) REFERENCES news_log(id)
);

CREATE INDEX idx_news_items_fecha_procesamiento
  ON news_items (fecha_procesamiento DESC);

CREATE INDEX idx_news_items_news_log
  ON news_items (news_log_id);