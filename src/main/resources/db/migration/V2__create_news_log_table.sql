
CREATE TABLE IF NOT EXISTS news_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio TIMESTAMPTZ NOT NULL,
    fecha_fin TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL,
    cantidad_noticias INTEGER NOT NULL DEFAULT 0,
    resumen TEXT,
    destinatarios TEXT,
    mensaje_error TEXT,

    CONSTRAINT chk_news_log_estado
        CHECK (estado IN ('SUCCESS', 'FAILED')),

    CONSTRAINT chk_news_log_cantidad
        CHECK (cantidad_noticias >= 0)
);

CREATE INDEX IF NOT EXISTS idx_news_log_fecha_inicio
    ON news_log (fecha_inicio DESC);
